def update_json_file(filepath, translations, language_name):
    """Update JSON file with translations"""
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    updated_count = 0
    for element, description in translations.items():
        if element in data:
            data[element]['description'] = description
            updated_count += 1
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"✅ {language_name}: Updated {updated_count} elements")
    return updated_count

