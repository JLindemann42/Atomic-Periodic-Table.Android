package com.jlindemann.science.model

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

/**
 * Pins the solubility table to `shared/golden/solubility.tsv`, which the Windows app checks its copy
 * against (roadmap 0.8). The two apps showed different tables until then, and the Windows one was
 * wrong in places; this is what keeps them one table.
 *
 * Kotlin is the source: after a deliberate change, regenerate with
 * `./gradlew :app:testDebugUnitTest --tests '*SolubilityGoldenTest' -Pgolden.update=true` and commit
 * the file in the shared repository.
 */
class SolubilityGoldenTest {

    private val golden: File? by lazy {
        listOf(File("../shared/golden"), File("shared/golden")).firstOrNull { it.isDirectory }
            ?.let { File(it, "solubility.tsv") }
    }

    private val columns = SolubilityData.getColumns()

    private fun render(): String = buildString {
        append("# The solubility table, generated by SolubilityGoldenTest.kt from Android's SolubilityModel.kt.\n")
        append("# S soluble, Ss slightly soluble, I insoluble, --- no stable compound in water.\n")
        append("# Both apps assert their table equals this. Do not edit by hand.\n")
        append("cation\t").append(SolubilityData.anions.joinToString("\t")).append('\n')
        for (column in columns) append(column.cation).append('\t').append(column.values.joinToString("\t")).append('\n')
    }

    @Test
    fun tableMatchesTheSharedGoldenFile() {
        val file = golden
        assumeTrue("shared/golden not reachable", file != null)
        if (System.getProperty("golden.update") == "true") {
            file!!.writeText(render(), Charsets.UTF_8)
            return
        }
        assertTrue("${file!!.path} is missing; run with -Pgolden.update=true", file.isFile)
        assertEquals(
            "solubility table changed; if deliberate, regenerate with -Pgolden.update=true",
            file.readText(Charsets.UTF_8).replace("\r\n", "\n"),
            render()
        )
    }

    @Test
    fun everyCellIsACode() {
        for (column in columns) {
            assertEquals(column.cation, SolubilityData.anions.size, column.values.size)
            for (value in column.values) assertTrue("${column.cation}: $value", value in setOf("S", "Ss", "I", "---"))
        }
        assertEquals(14, columns.size)
        assertEquals(14, SolubilityData.anions.size)
    }

    private fun cell(cation: String, anion: String): String =
        columns.single { it.cation == cation }.values[SolubilityData.anions.indexOf(anion)]

    /**
     * The cells the Windows page had wrong, and the solubility rules any chart must keep: alkali
     * metal, ammonium and nitrate salts dissolve; barium and lead sulfates and silver halides do not.
     */
    @Test
    fun theSolubilityRulesHold() {
        for (cation in listOf("Na^+", "K^+", "NH4^+")) {
            for (anion in SolubilityData.anions.filter { it != "SiO3^2-" }) assertEquals("$cation $anion", "S", cell(cation, anion))
        }
        for (column in columns) {
            if (column.cation != "H^+") assertEquals("${column.cation} nitrate", "S", cell(column.cation, "NO3^-"))
        }
        assertEquals("I", cell("Ba^2+", "SO4^2-"))
        assertEquals("I", cell("Pb^2+", "SO4^2-"))
        assertEquals("I", cell("Al^3+", "OH^-"))
        assertEquals("I", cell("Fe^3+", "OH^-"))
        for (halide in listOf("Cl^-", "Br^-", "I^-")) assertEquals("Ag $halide", "I", cell("Ag^+", halide))
        assertEquals("I", cell("Ca^2+", "SO3^2-"))
        assertEquals("S", cell("Na^+", "SiO3^2-"))
        assertEquals("I", cell("H^+", "SiO3^2-"))
    }
}
