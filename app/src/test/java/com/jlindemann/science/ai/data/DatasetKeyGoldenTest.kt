package com.jlindemann.science.ai.data

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

/**
 * Pins every dataset row's canonical key to `shared/golden/dataset_keys.tsv`, which the Windows app
 * checks its own keys against too (roadmap 0.6). A corpus row's `expect_row` names one of these, so
 * the two apps must agree on every one.
 *
 * Kotlin is the source: after a deliberate change to a dataset, regenerate the file with
 * `./gradlew :app:testDebugUnitTest --tests '*DatasetKeyGoldenTest' -Pgolden.update=true` and
 * commit it in the shared repository.
 */
class DatasetKeyGoldenTest {

    private val golden: File? by lazy {
        listOf(File("../shared/golden"), File("shared/golden")).firstOrNull { it.isDirectory }
            ?.let { File(it, "dataset_keys.tsv") }
    }

    private fun render(index: DatasetIndex): String = buildString {
        append("# Canonical dataset row keys, generated by DatasetKeyGoldenTest.kt from the Kotlin\n")
        append("# DatasetIndex. Both apps assert their keys equal these. Do not edit by hand.\n")
        append("key\tdataset\ttitle\n")
        for (row in index.rows) append(row.key).append('\t').append(row.dataset).append('\t')
            .append(row.title.replace('\t', ' ').replace('\n', ' ')).append('\n')
    }

    @Test
    fun keysMatchTheSharedGoldenFile() {
        val file = golden
        assumeTrue("shared/golden not reachable", file != null)
        val actual = render(DatasetIndex.build())
        if (System.getProperty("golden.update") == "true") {
            file!!.writeText(actual, Charsets.UTF_8)
            return
        }
        assertTrue("${file!!.path} is missing; run with -Pgolden.update=true", file.isFile)
        assertEquals(
            "dataset keys changed; if deliberate, regenerate with -Pgolden.update=true",
            file.readText(Charsets.UTF_8).replace("\r\n", "\n"),
            actual
        )
    }

    @Test
    fun everyKeyIsUnique() {
        val keys = DatasetIndex.build().rows.map { it.key }
        assertEquals(keys.size, keys.toSet().size)
    }

    /** Both Basalt rows in the Poisson table are citable — the second was unreachable by name. */
    @Test
    fun aRepeatedTitleGetsANumberedKey() {
        val index = DatasetIndex.build()
        assertTrue(index.byKey("poisson/basalt") != null)
        assertTrue(index.byKey("poisson/basalt#2") != null)
    }

    @Test
    fun slugsFoldToLowercaseAsciiWords() {
        assertEquals("planck-s-constant", DatasetIndex.slug("Planck's constant"))
        assertEquals("h2o", DatasetIndex.slug("H₂O"))
        assertEquals("cafe-au-lait", DatasetIndex.slug("Café au lait"))
        assertEquals("row", DatasetIndex.slug("—"))
    }
}
