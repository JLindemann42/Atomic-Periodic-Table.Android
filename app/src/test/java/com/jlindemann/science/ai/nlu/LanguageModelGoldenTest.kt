package com.jlindemann.science.ai.nlu

import com.jlindemann.science.ai.data.TestAssets
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.text.Normalizer

/**
 * Builds the language detector's model and pins it to `shared/language/trigrams.tsv`, which both
 * apps ship (roadmap 1.4).
 *
 * Kotlin is the source, as for the dataset keys: after changing the strings, the stopwords, the
 * element descriptions or the dataset titles, regenerate with
 * `./gradlew :app:testDebugUnitTest --tests '*LanguageModelGoldenTest' -Pgolden.update=true` and
 * commit the file in the shared repository. Never trained on the corpus, which is what measures it.
 */
class LanguageModelGoldenTest {

    private val model: File? by lazy {
        listOf(File("../shared"), File("shared")).firstOrNull { it.isDirectory }
            ?.let { File(it, "language/trigrams.tsv") }
    }

    @Test
    fun modelMatchesTheSharedFile() {
        val file = model
        assumeTrue("shared data not reachable", file != null && TestAssets.available())
        val actual = LanguageModelTraining.render()
        if (System.getProperty("golden.update") == "true") {
            file!!.parentFile.mkdirs()
            file.writeText(actual, Charsets.UTF_8)
            return
        }
        assertTrue("${file!!.path} is missing; run with -Pgolden.update=true", file.isFile)
        assertEquals(
            "the language model's sources changed; regenerate with -Pgolden.update=true",
            file.readText(Charsets.UTF_8).replace("\r\n", "\n"),
            actual
        )
    }

    @Test
    fun everyShippedLanguageIsModelled() {
        assumeTrue(TestAssets.available())
        val detector = LanguageDetector.parse(LanguageModelTraining.render())!!
        assertEquals(TestAssets.availableLanguages().sorted(), detector.languages)
    }
}

/** What the model is trained on, and how it is written down. */
object LanguageModelTraining {

    /** Trigrams kept per language; the rest count only towards the language's total. */
    const val KEPT = 3000

    /** The Latin-script languages, also trained on their text with the accents removed. */
    private val LATIN = setOf("en", "sv", "de", "es", "fr", "it", "pt", "af", "fil")

    private val res = listOf(File("src/main/res"), File("app/src/main/res")).first { it.isDirectory }

    fun render(): String {
        val languages = TestAssets.availableLanguages().sorted()
        val english = englishSentences()
        val englishStrings = strings("en")
        return buildString {
            append("# Character-trigram language model for Ask Atomic (roadmap 1.4), generated by\n")
            append("# LanguageModelGoldenTest.kt from the app strings, Lexicon.STOPWORDS, the element\n")
            append("# descriptions and datasets/titles_*.tsv. Do not edit by hand. A space is written _;\n")
            append("# the trigram * is the language's total, kept trigrams or not.\n")
            append("lang\ttrigram\tcount\n")
            for (lang in languages) {
                val counts = HashMap<String, Int>()
                for (text in texts(lang, english, englishStrings)) {
                    for (t in LanguageDetector.features(text)) counts.merge(t, 1, Int::plus)
                }
                append(lang).append('\t').append(LanguageDetector.TOTAL).append('\t').append(counts.values.sum()).append('\n')
                counts.entries
                    .sortedWith(compareByDescending<Map.Entry<String, Int>> { it.value }.thenBy { it.key })
                    .take(KEPT)
                    .forEach { (t, n) -> append(lang).append('\t').append(t.replace(' ', '_')).append('\t').append(n).append('\n') }
            }
        }
    }

    private fun texts(lang: String, english: Set<String>, englishStrings: Map<String, String>): List<String> {
        val texts = ArrayList<String>()
        // App strings, less any left in English: a fallback copied across is English evidence.
        strings(lang).forEach { (name, value) -> if (lang == "en" || englishStrings[name] != value) texts.add(value) }
        texts.addAll(Lexicon.STOPWORDS[lang].orEmpty())
        // Descriptions sentence by sentence, less the sentences still in English (roadmap 1.10).
        for (row in TestAssets.elementTable(lang).rows.values) {
            for (sentence in sentences(row["description"]?.toString().orEmpty())) {
                if (lang == "en" || sentence !in english) texts.add(sentence)
            }
        }
        TestAssets.text("titles_$lang.tsv")?.let { tsv ->
            tsv.lineSequence().filter { it.isNotBlank() && !it.startsWith("#") && !it.startsWith("key\t") }
                .forEach { line -> line.split('\t').getOrNull(1)?.split('|')?.forEach { texts.add(it) } }
        }
        // People type without accents as often as with them.
        if (lang in LATIN) texts.addAll(texts.map(::stripAccents).filter { it !in texts })
        return texts
    }

    private fun englishSentences(): Set<String> =
        TestAssets.elementTable("en").rows.values
            .flatMapTo(HashSet()) { sentences(it["description"]?.toString().orEmpty()) }

    private fun sentences(text: String): List<String> =
        text.split(Regex("""(?<=[.!?。！？۔।])\s*""")).map { it.trim() }.filter { it.isNotEmpty() }

    /** The values folders a language's strings live in, regional variants included. */
    private fun folders(lang: String): List<File> {
        val all = res.listFiles().orEmpty().filter { it.isDirectory }
        return when (lang) {
            "en" -> all.filter { it.name == "values" }
            "fil" -> all.filter { it.name == "values-b+fil" }
            else -> all.filter { it.name == "values-$lang" || it.name.startsWith("values-$lang-") }
        }.sortedBy { it.name }
    }

    /** Every translatable string and array item of a language, by name. */
    private fun strings(lang: String): Map<String, String> {
        val out = LinkedHashMap<String, String>()
        for (folder in folders(lang)) {
            val file = File(folder, "strings.xml")
            if (!file.isFile) continue
            val xml = file.readText(Charsets.UTF_8)
            for (m in STRING.findAll(xml)) {
                if ("translatable=\"false\"" in m.groupValues[2]) continue
                out.putIfAbsent(m.groupValues[1], clean(m.groupValues[3]))
            }
            var item = 0
            for (m in ITEM.findAll(xml)) out.putIfAbsent("item#${item++}", clean(m.groupValues[1]))
        }
        return out
    }

    private val STRING = Regex("""<string\s+name="([^"]+)"([^>]*)>(.*?)</string>""", RegexOption.DOT_MATCHES_ALL)
    private val ITEM = Regex("""<item[^>]*>(.*?)</item>""", RegexOption.DOT_MATCHES_ALL)

    private fun clean(value: String): String = value
        .replace(Regex("""<[^>]+>"""), " ")
        .replace(Regex("""%(\d+\$)?[a-zA-Z]"""), " ")
        .replace("\\n", " ").replace("\\'", "'").replace("\\\"", "\"")
        .replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", "\"").replace("&apos;", "'")

    private fun stripAccents(text: String): String =
        Normalizer.normalize(text, Normalizer.Form.NFD)
            .filter { Character.getType(it) != Character.NON_SPACING_MARK.toInt() }
}
